def validate():
    """뱅크 무결성 검사 — 각 주제 16아이템·타입키 일치·slug 중복 없음."""
    from collections import Counter
    seen, problems = set(), []
    for t in THEMES:
        s = t["slug"]
        if s in seen:
            problems.append(f"중복 slug: {s}")
        seen.add(s)
        if len(t["items"]) != 16:
            problems.append(f"{s}: items {len(t['items'])}개 (16이어야 함)")
        typekeys = set(t["types"].keys())
        for txt, key in t["items"]:
            if key not in typekeys:
                problems.append(f"{s}: 아이템 '{txt}' 의 타입키 '{key}' 미정의")
        dist = Counter(k for _, k in t["items"])
        for tk in typekeys:
            if not t["types"][tk].get("line"):
                problems.append(f"{s}: 타입 '{tk}' 에 line(한줄) 없음")
            if dist[tk] == 0:
                problems.append(f"{s}: 타입 '{tk}' 에 배정된 아이템 없음")
    return problems


